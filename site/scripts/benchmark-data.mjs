// Derive site/data/benchmark.json from benchmark/results/*.json.
//
// Runs before every build (prebuild). If ../benchmark/results isn't reachable (e.g. a
// deploy that only uploads site/), it keeps the committed data/benchmark.json as is.
// It never invents numbers: it copies measured values and marks missing arms "pending".
//
// Result files without a "stack" field are from the old hosted stack (v0, Postgres).
// Files with "stack": "local-first" are new-stack runs and replace the pending rows.
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const siteDir = join(here, "..");
const resultsDir = join(siteDir, "..", "benchmark", "results");
const outFile = join(siteDir, "data", "benchmark.json");

const V0_ARMS = {
  vector: "Vector only (pgvector)",
  keyword: "Keyword only (Postgres full-text)",
  hybrid: "Hybrid (RRF of both)",
};
const NEW_ARMS = {
  hybrid: "Chunk index, hybrid (RRF)",
  vector: "Chunk index, vector only",
  keyword: "Chunk index, keyword only",
  graph: "Chunks + graph facts (Graphiti)",
};
const METRICS = ["recall@5", "recall@10", "gold_coverage", "mrr", "p50_ms", "p95_ms"];

if (!existsSync(resultsDir)) {
  console.log(
    `benchmark-data: ${resultsDir} not found, keeping committed ${relative(siteDir, outFile)}`,
  );
  process.exit(0);
}

const runs = readdirSync(resultsDir)
  .filter((f) => f.endsWith(".json"))
  .sort()
  .map((f) => ({ file: f, data: JSON.parse(readFileSync(join(resultsDir, f), "utf8")) }));

const latest = (pred) => runs.filter((r) => pred(r.data)).at(-1);
const v0 = latest((d) => !d.stack || d.stack === "v0-hosted");
const next = latest((d) => typeof d.stack === "string" && d.stack.startsWith("local-first"));

function arms(run, names) {
  return Object.entries(names).map(([id, name]) => {
    const a = run?.data.arms?.[id];
    if (!a) return { id, name, status: "pending" };
    const metrics = Object.fromEntries(METRICS.map((m) => [m, a[m] ?? null]));
    return { id, name, status: "measured", n: a.n ?? null, ...metrics };
  });
}

function meta(run) {
  if (!run) return null;
  const d = run.data;
  return {
    file: `benchmark/results/${run.file}`,
    report: `benchmark/results/${run.file.replace(/\.json$/, ".md")}`,
    date: d.date ?? null,
    embedder: d.embedder ?? null,
    k: d.k ?? null,
    questions: d.dataset?.questions ?? null,
    documents: d.dataset?.indexed?.documents ?? null,
    chunks: d.dataset?.indexed?.chunks ?? null,
  };
}

const out = {
  note: "Generated by site/scripts/benchmark-data.mjs from benchmark/results/*.json. Do not edit by hand.",
  v0: v0
    ? {
        label: "v0 (Postgres) baseline",
        stack: "Old hosted stack: Postgres + pgvector + Postgres full-text search",
        ...meta(v0),
        arms: arms(v0, V0_ARMS),
      }
    : null,
  next: {
    label: "Local-first stack (Neo4j)",
    status: next ? "measured" : "pending",
    ...(meta(next) ?? {}),
    arms: arms(next, NEW_ARMS),
  },
};

writeFileSync(outFile, JSON.stringify(out, null, 2) + "\n");
console.log(
  `benchmark-data: wrote ${relative(siteDir, outFile)} (v0: ${v0?.file ?? "none"}, new stack: ${next?.file ?? "pending"})`,
);
